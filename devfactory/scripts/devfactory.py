def hash_files(files):
    """One hash over (name, content) pairs, content with LF line endings."""
    parts = []
    for name, content in files:
        parts.append('%s\n%d\n%s' % (name, len(content), content))
    return sha256('\n'.join(parts))


def profile_hash(root):
    files = []
    pf = profile_file(root)
    if os.path.exists(pf):
        files.append(('profile.md', read_text(pf)))
    mods = os.path.join(root, '.devfactory', 'modules')
    if os.path.isdir(mods):
        for f in sorted(list_files(mods)):
            files.append(('modules/' + f, read_text(os.path.join(mods, f))))
    return hash_files(files)


def facts_hash(file):
    lines = [re.sub(r'\s+', ' ', l).strip() for l in read_text(file).split('\n')]
    return sha256('\n'.join(sorted(l for l in lines if l)))


def specs_path(root):
    try:
        p = profile_field(read_profile(root), 'Specs', 'Path')
    except UsageError:
        p = None
    p = (p or 'specs/').strip().strip('`').strip() or 'specs/'
    return p.replace('\\', '/').strip('/')


def specs_content_hash(root, dirs):
    files = []
    for d in dirs:
        full = os.path.join(root, d)
        if not os.path.isdir(full):
            raise UsageError('no spec folder %s' % d)
        for f in sorted(list_files(full)):
            if f == RECEIPTS:
                continue
            content = read_text(os.path.join(full, f))
            if f == 'spec.md':
                content = STATUS_ROW.sub(r'\1 |', content)
            files.append((d + '/' + f, content))
    return hash_files(files)


def gap_sources_hash(root):
    files = []
    ledger = os.path.join(root, '.devfactory', 'gaps.md')
    if os.path.exists(ledger):
        files.append(('.devfactory/gaps.md', read_text(ledger)))
    sp = os.path.join(root, specs_path(root))
    if os.path.isdir(sp):
        for f in sorted(list_files(sp)):
            if f == 'gaps.md' or f.endswith('/gaps.md'):
                files.append((f, read_text(os.path.join(sp, f))))
    return hash_files(files)


def git_head(root):
    r = run_process(['git', 'rev-parse', 'HEAD'], cwd=root)
    if r.returncode != 0:
        raise UsageError('git rev-parse HEAD failed: %s' % decode(r.stderr).strip())
    return decode(r.stdout).strip()


def code_unchanged(root, commit):
    """True when HEAD descends from commit and nothing outside the specs path and .devfactory/
    differs between them; those are fingerprinted on their own."""
    r = run_process(['git', 'merge-base', '--is-ancestor', commit, 'HEAD'], cwd=root)
    if r.returncode != 0:
        return False
    r = run_process(['git', 'diff', '--quiet', commit, 'HEAD', '--', '.',
                     ':(exclude)%s' % specs_path(root), ':(exclude).devfactory'], cwd=root)
    return r.returncode == 0


def read_spec_list(root, file):
    dirs = [l.strip().replace('\\', '/').strip('/') for l in read_text(file).split('\n') if l.strip()]
    if not dirs:
        raise UsageError('%s names no spec folder' % file)
    out = []
    for d in dirs:
        full = os.path.abspath(os.path.join(os.getcwd(), d))
        out.append(os.path.relpath(full, root).replace(os.sep, '/'))
    return sorted(set(out))


def receipt_fingerprint(check, opts, root):
    if check == 'request':
        if not opts.get('facts'):
            raise UsageError('give --facts <file>')
        card = read_card(opts)
        return {'Card revision': card_revision(card['title'], card['body']),
                'Card facts': facts_hash(opts['facts']),
                'Standard': standard_version(),
                'Profile': profile_hash(root)}
    if not opts.get('specs'):
        raise UsageError('give --specs <file>')
    dirs = read_spec_list(root, opts['specs'])
    return {'Specs': ', '.join(dirs),
            'Specs content': specs_content_hash(root, dirs),
            'Gap sources': gap_sources_hash(root),
            'Standard': standard_version(),
            'Profile': profile_hash(root),
            'Repo commit': git_head(root)}


def parse_receipts(text):
    out = {}
    current = None
    for line in to_lf(text).split('\n'):
        m = rx(r'^##\s+(.+?)\s*\Z').match(line)
        if m:
            current = m.group(1)
            out[current] = {}
            continue
        f = profile_field_line(line)
        if current and f:
            out[current][f['name']] = f['value']
    return out


def format_receipts(receipts):
    blocks = ['# Receipts\n\nEach passing check\'s fingerprint of what it read; `devfactory receipt check` '
              'compares it before a later stage judges again.']
    for check in ('request', 'ready'):
        title = RECEIPT_CHECKS[check]
        if title in receipts:
            r = receipts[title]
            names = RECEIPT_FIELDS[check] + ['Checked']
            blocks.append('## %s\n\n' % title + '\n'.join('- %s: %s' % (n, r.get(n, '')) for n in names))
    return '\n\n'.join(blocks) + '\n'


def cmd_receipt(opts):
    sub = opts['_'][0] if opts['_'] else None
    d = opts['_'][1] if len(opts['_']) > 1 else None
    if sub not in ('write', 'check') or not d:
        raise UsageError('give receipt write|check <spec dir> --check request|ready')
    check = opts.get('check')
    if check not in RECEIPT_CHECKS:
        raise UsageError('--check must be request or ready')
    root = project_root()
    file = os.path.join(d, RECEIPTS)
    receipts = parse_receipts(read_text(file)) if os.path.exists(file) else {}
    now = receipt_fingerprint(check, opts, root)
    title = RECEIPT_CHECKS[check]
    if sub == 'write':
        os.makedirs(d, exist_ok=True)
        receipts[title] = dict(now, Checked=today())
        with open(file, 'wb') as f:
            f.write(utf8(format_receipts(receipts)))
        return ['wrote %s %s' % (check, file)], 0
    old = receipts.get(title)
    if not old:
        return ['no-receipt %s' % check], 1
    out = []
    for name in RECEIPT_FIELDS[check]:
        if name == 'Repo commit':
            if not code_unchanged(root, old.get(name, '')):
                out.append('differs Repo commit %s %s' % (old.get(name, ''), now[name]))
        elif old.get(name, '') != now[name]:
            out.append('differs %s %s %s' % (name, old.get(name, ''), now[name]))
    return (out, 1) if out else (['match %s' % check], 0)

# ---------- the project root, profile and markers ----------


def project_root(d=None):
    """The repository root of the effective directory (a worktree's own root), else the directory."""
    d = d or os.getcwd()
    top = ''
    try:
        r = run_process(['git', 'rev-parse', '--show-toplevel'], cwd=d)
        if r.returncode == 0:
            top = decode(r.stdout).strip()
    except (OSError, subprocess.SubprocessError):
        top = ''
    return os.path.abspath(top or d)


def profile_file(root):
    return os.path.join(root, '.devfactory', 'profile.md')


def marker_dir(root):
    return os.path.join(root, '.devfactory', '.active')


PROFILE_HEADING = rx(r'^(#{1,6})\s+(.+?)\s*#*\s*\Z')


def profile_sections(text):
    """The profile's sections, from any heading level to the next heading at the same or a
    higher level, so a section holds its subsections."""
    lines = to_lf(text).split('\n')
    sections = []
    for i, l in enumerate(lines):
        h = PROFILE_HEADING.search(l)
        if h:
            sections.append({'title': h.group(2).strip(), 'level': len(h.group(1)), 'start': i})
    for s in sections:
        nxt = next((o for o in sections if o['start'] > s['start'] and o['level'] <= s['level']), None)
        s['lines'] = lines[s['start'] + 1:nxt['start'] if nxt else len(lines)]
    return {'lines': lines, 'sections': sections}


FIELD_BOLD = rx(r'^\s*[-*]\s+\*\*([^*]+?)(?::\*\*|\*\*\s*:)\s*(.*?)\s*\Z')
FIELD_BARE = rx(r'^\s*[-*]\s+([^:*`][^:*]*?)\s*:\s*(.*?)\s*\Z')


def profile_field_line(line):
    """A profile field line in any of the forms people write: "- Name: value", "* Name: value",
    "- **Name:** value" and "- **Name**: value". Returns {name, value} or None."""
    bold = FIELD_BOLD.search(line)
    if bold:
        return {'name': bold.group(1).strip(), 'value': bold.group(2)}
    bare = FIELD_BARE.search(line)
    if bare:
        return {'name': bare.group(1).strip(), 'value': bare.group(2)}
    return None


def read_profile(root):
    file = profile_file(root)
    if not os.path.exists(file):
        raise UsageError('no profile at %s' % file)
    return profile_sections(read_text(file))


def profile_section_lines(profile, name):
    s = next((o for o in profile['sections'] if o['title'].lower() == name.lower()), None)
    return s['lines'] if s else None


def profile_field(profile, section, field):
    lines = profile_section_lines(profile, section) if section else profile['lines']
    if lines is None:
        return None
    for l in lines:
        f = profile_field_line(l)
        if f and f['name'].lower() == field.lower():
            return f['value']
    return None


def marker_lifetime_hours(root):
    """The Hooks section's "Marker lifetime: <hours>h", default 12 hours."""
    try:
        value = profile_field(read_profile(root), 'Hooks', 'Marker lifetime')
    except Exception:
        value = None
    m = rx(r'^`?(\d+(?:\.\d+)?)\s*h?\b', re.I).search(value or '')
    hours = float(m.group(1)) if m else float('nan')
    return hours if hours > 0 else DEFAULT_MARKER_HOURS


def age(ms):
    s = max(0, math.floor(ms / 1000 + 0.5))
    if s < 60:
        return '%ds' % s
    if s < 3600:
        return '%dm' % (s // 60)
    if s < 86400:
        return '%dh' % (s // 3600)
    return '%dd' % (s // 86400)


def list_markers(root):
    """Every marker with its time and whether it is older than the lifetime."""
    d = marker_dir(root)
    if not os.path.exists(d):
        return []
    lifetime = marker_lifetime_hours(root)
    out = []
    for name in sorted(os.listdir(d)):
        if name.startswith('.'):
            continue
        file = os.path.join(d, name)
        st = os.stat(file)
        if not os.path.isfile(file):
            continue
        t = parse_iso_ms(read_raw(file))
        if t is None:
            t = st.st_mtime * 1000
        ms = now_ms() - t
        out.append({'name': name, 'file': file, 'time': iso_from_ms(t), 'age': age(ms),
                    'stale': ms > lifetime * 3600000, 'lifetime': lifetime})
    return out


def describe_marker(m):
    if m['stale']:
        return 'stale %s since %s (%s ago, older than %sh; the guards ignore it)' % (
            m['name'], m['time'], m['age'], js_number(m['lifetime']))
    return 'active %s since %s (%s ago)' % (m['name'], m['time'], m['age'])


def skill_name(opts):
    name = opts['_'][0] if opts['_'] else None
    if not name or not rx(r'[A-Za-z0-9._-]+').fullmatch(name):
        raise UsageError('give a skill name (letters, digits, . _ -)')
    return name


def cmd_begin(opts):
    name = skill_name(opts)
    root = project_root()
