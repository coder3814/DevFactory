def cmd_stamp_check(opts):
    if not opts.get('spec'):
        raise UsageError('give --spec <dir>')
    spec_file = os.path.join(opts['spec'], 'spec.md')
    if not os.path.exists(spec_file):
        raise UsageError('no spec.md in %s' % opts['spec'])
    rows = header_rows(split_sections(read_text(spec_file)))
    m = rx(r'[0-9a-f]{64}', re.I).search(rows.get('Card revision') or '')
    old_rev = m.group(0) if m else None
    m = rx(r'\b[0-9a-f]{7,40}\b', re.I).search(rows.get('Repo commit') or '')
    commit = m.group(0) if m else None
    if not old_rev:
        raise UsageError('%s has no Card revision hash' % spec_file)
    if not commit:
        raise UsageError('%s has no Repo commit' % spec_file)
    card = read_card(opts)
    new_rev = card_revision(card['title'], card['body'])
    out = []
    matched = old_rev.lower() == new_rev
    out.append('match' if matched else 'changed %s %s' % (old_rev.lower(), new_rev))
    try:
        r = run_process(['git', 'merge-base', '--is-ancestor', commit, 'HEAD'])
    except OSError as e:
        raise UsageError('cannot run git: %s' % e)
    if r.returncode not in (0, 1):
        raise UsageError('git merge-base failed: %s' % decode(r.stderr).strip())
    ancestor = r.returncode == 0
    out.append('ancestor' if ancestor else 'not-ancestor')
    return out, 0 if matched and ancestor else 1


TYPE_SPLIT = rx(r'\s*(?:,|;|/|\band\b)\s*')


def lint_spec(d, criteria):
    findings = []
    spec_file = os.path.join(d, 'spec.md')
    if not os.path.exists(spec_file):
        raise UsageError('no spec.md in %s' % d)
    doc = split_sections(read_text(spec_file))

    rows = header_rows(doc)
    status = rows.get('Status')
    for name in HEADER_ROWS:
        if name not in rows:
            findings.append('header-missing %s' % name)
        elif not rows[name] and not (status == 'drafting' and name in STAMP_ROWS):
            findings.append('header-empty %s' % name)
    if status and status not in STATUSES:
        findings.append('status-invalid "%s" is not one of %s' % (status, ', '.join(STATUSES)))
    types = rows.get('Request type(s)')
    if types:
        for t in [s.strip() for s in TYPE_SPLIT.split(types) if s.strip()]:
            if t.lower() not in REQUEST_TYPES:
                findings.append('request-type-invalid "%s" is not one of %s' % (t, ', '.join(REQUEST_TYPES)))
    if status in STAMPED_STATUSES:
        rev = (rows.get('Card revision') or '').replace('`', '').strip()
        commit = (rows.get('Repo commit') or '').replace('`', '').strip()
        if rev and not rx(r'[0-9a-f]{64}').fullmatch(rev):
            findings.append('card-revision-invalid "%s" is not 64 lowercase hex characters' % rev)
        if commit and not rx(r'[0-9a-f]{7,40}', re.I).fullmatch(commit):
            findings.append('repo-commit-invalid "%s" is not a 7 to 40 character hex commit' % commit)
        stamped = (rows.get('Stamped') or '').replace('`', '').strip()
        if stamped and not rx(r'\d{4}-\d{2}-\d{2}').fullmatch(stamped):
            findings.append('stamped-invalid "%s" is not a YYYY-MM-DD date' % stamped)

    last = -1
    for s in doc['sections']:
        idx = next((i for i, r in enumerate(SECTIONS) if r['name'].lower() == s['title'].lower()), -1)
        if idx < 0:
            continue
        if idx < last:
            findings.append('section-order "%s" comes after "%s"' % (SECTIONS[idx]['name'], SECTIONS[last]['name']))
        else:
            last = idx
    for r in SECTIONS:
        if not r.get('optional') and not find_section(doc, r['name']):
            findings.append('section-missing %s' % r['name'])

    disp = find_section(doc, 'Dispositions')
    if disp:
        tables = parse_tables(disp['lines'])
        if not tables:
            findings.append('dispositions-no-table the Dispositions section has no table')
        else:
            t = tables[0]
            c = column(t, lambda h: h == 'disposition')
            concern = column(t, lambda h: h == 'concern')
            name_col = 0 if concern < 0 else concern
            for i, row in enumerate(t['rows']):
                if c < 0 or not plain(cell(row, c)) or is_italic_prompt(cell(row, c)):
                    findings.append('disposition-blank %s' % (plain(cell(row, name_col)) or 'row %d' % (i + 1)))
            present = set(plain(cell(row, name_col)).lower() for row in t['rows'])
            for name in CORE_CONCERNS:
                if name.lower() not in present:
                    findings.append('disposition-missing %s has no row' % name)

    ev = find_section(doc, 'Evidence plan')
    if ev:
        tables = parse_tables(ev['lines'])
        t = tables[0] if tables else None
        if not t:
            findings.append('evidence-no-table the Evidence plan section has no table')
        else:
            for name in EVIDENCE_COLUMNS:
                if column(t, lambda h, n=name.lower(): h == n) < 0:
                    findings.append('evidence-column-missing %s' % name)
        if t and criteria is not None:
            c = column(t, lambda h: h == 'criterion')
            planned = []
            for row in t['rows']:
                for i in criterion_ids_in('' if c < 0 else cell(row, c)):
                    if i not in planned:
                        planned.append(i)
            for i in criteria:
                if i not in planned:
                    findings.append('evidence-missing %s has no evidence row' % i)
            known = set(criteria)
            for i in planned:
                if i not in known:
                    findings.append('evidence-unknown %s is not a criterion of the card' % i)

    owner = find_section(doc, 'Owner steps')
    if owner:
        for t in parse_tables(owner['lines'])[:1]:
            m = column(t, lambda h: h.startswith('moment'))
            step = column(t, lambda h: h == 'step')
            for i, row in enumerate(t['rows']):
                if m < 0 or not plain(cell(row, m)):
                    findings.append('owner-step-no-moment %s' % (plain(cell(row, 0 if step < 0 else step)) or 'row %d' % (i + 1)))

    am = find_section(doc, 'Amendments')
    if am:
        tables = parse_tables(am['lines'])
        if not tables or len(tables[0]['rows']) == 0:
            findings.append('amendments-empty the Amendments table has no row')

    gaps = load_gaps(d)
    if gaps:
        for e in gaps['errors']:
            findings.append('gaps-parse %s' % e)
    return findings


def cmd_spec_lint(opts):
    d = opts['_'][0] if opts['_'] else None
    if not d:
        raise UsageError('give the spec folder')
    criteria = read_id_list(opts['criteria']) if opts.get('criteria') else None
