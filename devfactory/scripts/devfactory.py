STATUS_ROW = rx(r'^(\|\s*\*\*Status\*\*\s*\|).*$', re.M)


def standard_version():
    file = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '.claude-plugin', 'plugin.json')
