AC_HEADING = rx(r'^#{1,6}\s+acceptance criteria\b', re.I)
CRITERION_LINE = rx(r'^\s*(?:[-*+]|\d+[.)])\s+(?:\*\*|__)?(C\d+)\b')


def criteria_ids(body):
    """Criterion IDs in a card: C<n> opening a list item, within "Acceptance criteria" if present."""
    doc = to_lf(body).split('\n')
    lines = doc
    start = next((i for i, l in enumerate(doc) if AC_HEADING.search(l.strip())), -1)
    if start >= 0:
        level = len(rx(r'^(#+)').search(doc[start].strip()).group(1))
        end = len(doc)
        for i in range(start + 1, len(doc)):
            h = rx(r'^(#+)\s').search(doc[i].strip())
            if h and len(h.group(1)) <= level:
                end = i
                break
        lines = doc[start + 1:end]
    ids = []
    for l in lines:
        m = CRITERION_LINE.search(l)
        if m:
            ids.append(m.group(1))
    return ids


def cmd_criteria_ids(opts):
    card = read_card(opts)
    ids = criteria_ids(card['body'])
    seen = set()
    out = []
    dups = []
    for i in ids:
        if i in seen:
            if i not in dups:
                dups.append(i)
        else:
            seen.add(i)
            out.append(i)
    for d in dups:
        out.append('duplicate %s opens more than one criterion' % d)
    return out, 1 if dups else 0


def cmd_gaps(opts):
    pos = opts['_']
    sub = pos[0] if len(pos) > 0 else None
    d = pos[1] if len(pos) > 1 else None
    if not sub or not d:
        raise UsageError('give gaps add|check|ledger <dir>')
    if not os.path.isdir(d):
        raise UsageError('no folder %s' % d)
    if sub == 'add':
        for k in ['stage', 'question', 'condition']:
            if not opts.get(k):
                raise UsageError('gaps add needs --%s' % k)
        if opts['stage'] not in GAP_STAGES:
            raise UsageError('--stage must be one of %s' % ', '.join(GAP_STAGES))
        fields = {
            'question': one_line(opts['question']),
            'condition': one_line(opts['condition']),
            'resolved': one_line(opts.get('resolved') or 'open'),
        }
        append_block(os.path.join(d, 'gaps.md'), '## %s — %s\n\n%s' % (today(), opts['stage'], format_gap_body(fields)))
        return [], 0
    if sub == 'check':
        gaps = load_gaps(d)
        if not gaps:
            return [], 0
        out = ['gaps-parse %s' % e for e in gaps['errors']]
        for e in gaps['entries']:
            if (e['fields'].get('resolved') or '').lower() == 'open':
                out.append('gap-open %s — %s: %s' % (e['date'], e['stage'], e['fields'].get('question')))
        return out, 1 if out else 0
    if sub == 'ledger':
        for k in ['card', 'types', 'ledger']:
            if not opts.get(k):
                raise UsageError('gaps ledger needs --%s' % k)
        gaps = load_gaps(d)
        if not gaps:
            return ['appended 0'], 0
        if gaps['errors']:
            return ['gaps-parse %s' % e for e in gaps['errors']], 1
        blocks = ['## %s (%s) — %s — %s\n\n%s' % (opts['card'], opts['types'], e['date'], e['stage'], format_gap_body(e['fields']))
                  for e in gaps['entries']]
        if blocks:
            append_block(opts['ledger'], '\n\n'.join(blocks))
        return ['appended %d' % len(blocks)], 0
    raise UsageError('unknown gaps subcommand "%s"' % sub)


def list_files(d, base=None):
    base = d if base is None else base
    out = []
    for ent in os.scandir(d):
        if ent.is_dir(follow_symlinks=False):
            out.extend(list_files(ent.path, base))
        else:
            out.append(os.path.relpath(ent.path, base).replace(os.sep, '/'))
    return out


