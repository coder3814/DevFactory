# ---------- text helpers ----------


def to_lf(s):
    return re.sub(r'\r\n?', '\n', str(s))


def read_raw(file):
    with open(file, 'r', encoding='utf-8', errors='replace', newline='') as f:
        return f.read()


def read_text(file):
    try:
        raw = read_raw(file)
    except OSError as e:
        raise UsageError('cannot read %s: %s' % (file, e.strerror or e))
    if raw.startswith('﻿'):
        raw = raw[1:]
    return to_lf(raw)


def read_id_list(file):
    return [l.strip() for l in read_text(file).split('\n') if l.strip() != '']


def one_line(s):
    return ' '.join(l.strip() for l in to_lf(s).split('\n') if l.strip())


def today():
    return datetime.date.today().strftime('%Y-%m-%d')


def utf8(s):
    # UTF-8 with any lone surrogate as U+FFFD, as Node encodes it.
    return s.encode('utf-16', 'surrogatepass').decode('utf-16', 'replace').encode('utf-8')


def sha256(s):
    return hashlib.sha256(utf8(s)).hexdigest()


def iso_from_ms(ms):
    # JavaScript's Date#toISOString: UTC with milliseconds and a Z.
    ms = int(ms)
    d = datetime.datetime(1970, 1, 1, tzinfo=datetime.timezone.utc) + datetime.timedelta(milliseconds=ms)
    return d.strftime('%Y-%m-%dT%H:%M:%S.') + '%03dZ' % (d.microsecond // 1000)


def now_ms():
    return time.time() * 1000


def parse_iso_ms(s):
    """An ISO 8601 timestamp in epoch milliseconds, or None. A date alone is UTC and a time
    without an offset is local time, as JavaScript's Date.parse reads them."""
    s = s.strip()
    if not s:
        return None
    try:
        if rx(r'\d{4}-\d{2}-\d{2}\Z').match(s):
            d = datetime.datetime.strptime(s, '%Y-%m-%d').replace(tzinfo=datetime.timezone.utc)
        else:
            d = datetime.datetime.fromisoformat(s[:-1] + '+00:00' if s[-1:] in ('Z', 'z') else s)
    except (ValueError, OverflowError, OSError):
        return None
    return math.floor(d.timestamp() * 1000)


def js_number(n):
    return str(int(n)) if float(n).is_integer() else repr(float(n))


def run_process(args, cwd=None, timeout=None):
    return subprocess.run(args, cwd=cwd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, timeout=timeout, creationflags=NO_WINDOW)


def decode(b):
    return (b or b'').decode('utf-8', errors='replace')

# ---------- the stamp ----------


def card_text(title, body):
    """The card text as spec-template.md's "The stamp" defines it."""
    lines = [l for l in to_lf(body or '').split('\n') if not SPEC_LINE.search(l)]
    clean_body = re.sub(r'\n+\Z', '', '\n'.join(lines))
    return re.sub(r'\n+\Z', '', to_lf(title or '')) + '\n' + clean_body


def card_revision(title, body):
    return sha256(card_text(title, body))


def split_text_card(text):
    """A --text file: first line the title, the rest the body."""
    t = to_lf(text)
    i = t.find('\n')
    return {'title': t, 'body': ''} if i < 0 else {'title': t[:i], 'body': t[i + 1:]}


def gh_issue(card, repo):
    n = re.sub(r'^#', '', str(card), count=1)
    if not rx(r'^\d+\Z').match(n):
        raise UsageError('card must be an issue number, got "%s"' % card)
    args = ['gh', 'issue', 'view', n, '--json', 'title,body']
    if repo:
        args += ['--repo', repo]
    try:
        r = run_process(args)
    except OSError as e:
        raise UsageError('cannot run gh: %s' % e)
    if r.returncode != 0:
        raise UsageError('gh issue view %s failed: %s' % (n, decode(r.stderr).strip()))
    try:
        j = json.loads(decode(r.stdout))
    except ValueError:
        raise UsageError('gh issue view returned invalid JSON')
    if not isinstance(j, dict):
        j = {}
    return {'title': j.get('title') or '', 'body': j.get('body') or ''}


def read_card(opts):
    if opts.get('text'):
        return split_text_card(read_text(opts['text']))
    if opts.get('card'):
        return gh_issue(opts['card'], opts.get('repo'))
    raise UsageError('give --card <n> or --text <file>')

# ---------- Markdown parsing ----------


def clean_heading(s):
    s = rx(r'\s*\*\([^)]*\)\*\s*\Z').sub('', s, count=1)
    s = rx(r'\s+#+\s*\Z').sub('', s, count=1)
    return s.strip()


def split_sections(text):
    """Splits a document into the lines before the first "## " heading and its "## " sections."""
    out = {'preamble': [], 'sections': []}
    cur = None
    fence = False
    for line in to_lf(text).split('\n'):
        if rx(r'^\s*(```|~~~)').search(line):
            fence = not fence
        m = None if fence else rx(r'^##\s+(.+)\Z').search(line)
        if m:
            cur = {'title': clean_heading(m.group(1)), 'lines': []}
            out['sections'].append(cur)
            continue
        (cur['lines'] if cur else out['preamble']).append(line)
    return out


def split_row(line):
    s = line.strip()
    if s.startswith('|'):
        s = s[1:]
    if s.endswith('|') and not s.endswith('\\|'):
        s = s[:-1]
    return [c.strip() for c in re.split(r'(?<!\\)\|', s)]


SEPARATOR = rx(r'^\|?(\s*:?-+:?\s*\|)*\s*:?-+:?\s*\|?\Z')


def is_separator(line):
    return bool(SEPARATOR.search(line.strip()))


def parse_tables(lines):
    """Every pipe table in the lines, as {header, rows}."""
    tables = []
    i = 0
    while i < len(lines):
        if not lines[i].strip().startswith('|'):
            i += 1
            continue
        block = []
        while i < len(lines) and lines[i].strip().startswith('|'):
            block.append(lines[i])
            i += 1
        if len(block) >= 2 and is_separator(block[1]):
            tables.append({'header': split_row(block[0]), 'rows': [split_row(b) for b in block[2:]]})
    return tables


def cell(row, i):
    return row[i] if 0 <= i < len(row) else None


def plain(c):
    return (c or '').replace('**', '').strip()


def column(table, predicate):
    for i, h in enumerate(table['header']):
        if predicate(plain(h).lower()):
            return i
    return -1


def find_section(doc, name):
    for s in doc['sections']:
        if s['title'].lower() == name.lower():
            return s
    return None


def header_rows(doc):
    tables = parse_tables(doc['preamble'])
    rows = {}
    if not tables:
        return rows
    table = tables[0]
    for row in [table['header']] + table['rows']:
        name = plain(cell(row, 0))
        if name and name not in rows:
            rows[name] = plain(cell(row, 1))
    return rows


def is_italic_prompt(c):
    """A cell holding only the template's italic prompt (one *...* span) has not been answered."""
    return bool(rx(r'^\*[^*]+\*\Z').search((c or '').strip()))


def criterion_ids_in(c):
    return rx(r'\bC\d+\b').findall(c or '')

# ---------- gaps.md ----------


GAP_HEADING = rx(r'^##\s+(\d{4}-\d{2}-\d{2})\s+[—–-]\s+(.+?)\s*\Z')
GAP_FIELD = rx(r'^\s*[-*]\s+\*\*([^*]+?)\*\*\s*(.*)\Z')


def parse_gaps(text):
    entries = []
    errors = []
    cur = None
    last_field = None
    for idx, line in enumerate(to_lf(text).split('\n')):
        n = idx + 1
        if rx(r'^##\s').search(line):
            m = GAP_HEADING.search(line)
            last_field = None
            if not m:
                errors.append('line %d: heading is not "## <date> — <stage>"' % n)
                cur = None
                continue
            cur = {'date': m.group(1), 'stage': m.group(2), 'fields': {}, 'line': n}
            entries.append(cur)
            continue
        if line.strip() == '':
            continue
        if rx(r'^#\s').search(line) and len(entries) == 0:
            continue
        f = GAP_FIELD.search(line)
        if f and cur:
            label = rx(r':\s*\Z').sub('', f.group(1), count=1).strip().lower()
            field = next((g for g in GAP_FIELDS if g['label'].lower() == label), None)
            if not field:
                errors.append('line %d: unknown field "%s"' % (n, f.group(1)))
                last_field = None
                continue
            cur['fields'][field['key']] = rx(r'^:\s*').sub('', f.group(2), count=1).strip()
            last_field = field['key']
            continue
        if cur and last_field and rx(r'^\s+\S').search(line):
            cur['fields'][last_field] = (cur['fields'][last_field] + ' ' + line.strip()).strip()
            continue
        errors.append("line %d: text outside an entry's fields" % n)
    for e in entries:
        if e['stage'] not in GAP_STAGES:
            errors.append('line %d: stage "%s" is not one of %s' % (e['line'], e['stage'], ', '.join(GAP_STAGES)))
        for g in GAP_FIELDS:
            if not e['fields'].get(g['key']):
                errors.append('line %d: entry has no "%s"' % (e['line'], g['label']))
    return {'entries': entries, 'errors': errors}


def format_gap_body(fields):
    return '\n'.join('- **%s:** %s' % (g['label'], fields.get(g['key'])) for g in GAP_FIELDS)


def append_block(file, block):
    prefix = ''
    if os.path.exists(file):
        existing = read_raw(file)
        if len(existing) > 0:
            if rx(r'\n\s*\n\Z').search(to_lf(existing)):
                prefix = ''
            elif existing.endswith('\n'):
                prefix = '\n'
            else:
                prefix = '\n\n'
    else:
        os.makedirs(os.path.dirname(os.path.abspath(file)), exist_ok=True)
    with open(file, 'ab') as f:
        f.write(utf8(prefix + block + '\n'))


def load_gaps(d):
    file = os.path.join(d, 'gaps.md')
    if not os.path.exists(file):
        return None
    return parse_gaps(read_text(file))

