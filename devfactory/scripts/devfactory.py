# ---------- events ----------

EVENTS = ['request-met', 'ready', 'approved', 'work-started', 'development-started', 'readiness-lost', 'done', 'refused', 'accepted', 'released']
EVENT_TIMEOUT_SECONDS = 300


def event_runner(file):
    ext = os.path.splitext(file)[1].lower()
    if ext == '.py':
        return [sys.executable, file]
    if ext == '.ps1':
        return ['powershell', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', file]
    if ext in ('.cmd', '.bat'):
        return ['cmd', '/c', file]
    if ext in ('', '.sh'):
        return [find_bash(), file]
    raise OSError('no runner for "%s" files (use .py, .ps1, .cmd, .bat, .sh or none)' % ext)


def find_bash():
    """bash on PATH; on Windows, never System32's WSL launcher, which cannot take a Windows path."""
    system32 = os.path.normcase(os.path.join(os.environ.get('SystemRoot', r'C:\Windows'), 'System32'))
    for d in os.environ.get('PATH', '').split(os.pathsep):
        for name in (['bash.exe'] if os.name == 'nt' else ['bash']):
            f = os.path.join(d, name)
            if os.path.isfile(f) and not (os.name == 'nt' and os.path.normcase(os.path.dirname(f)) == system32):
                return f
    raise OSError('no bash found on PATH')


def kill_tree(proc):
    if os.name == 'nt':
        subprocess.run(['taskkill', '/T', '/F', '/PID', str(proc.pid)], stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL, creationflags=NO_WINDOW)
    proc.kill()


def cmd_event(opts):
    name = opts['_'][0] if opts['_'] else None
    if name not in EVENTS:
        raise UsageError('give an event: %s' % ', '.join(EVENTS))
    card = opts.get('card')
    if not card:
        raise UsageError('give --card <id>')
    root = project_root()
    d = os.path.join(root, '.devfactory', 'hooks')
    found = sorted(f for f in (os.listdir(d) if os.path.isdir(d) else [])
                   if os.path.splitext(f)[0].lower() == name and os.path.isfile(os.path.join(d, f)))
    if not found:
        return ['no-hook %s' % name], 0
    if len(found) > 1:
        raise UsageError('more than one hook for %s: %s' % (name, ', '.join(found)))
    file = os.path.join(d, found[0])
    env = dict(os.environ, DEVFACTORY_EVENT=name, DEVFACTORY_CARD=card)
    # Output goes to a file, not a pipe, so a killed hook's children cannot hold the wait open.
    with tempfile.TemporaryFile() as log:
        try:
            proc = subprocess.Popen(event_runner(file) + [card], cwd=root, env=env, stdin=subprocess.DEVNULL,
                                    stdout=log, stderr=subprocess.STDOUT, creationflags=NO_WINDOW)
        except OSError as e:
            return ['hook-failed %s could not start: %s' % (found[0], e)], 1
        try:
            code = proc.wait(timeout=EVENT_TIMEOUT_SECONDS)
        except subprocess.TimeoutExpired:
            kill_tree(proc)
            return ['hook-failed %s timed out after %ds' % (found[0], EVENT_TIMEOUT_SECONDS)], 1
        log.seek(0)
        out = [l for l in decode(log.read()).replace('\r\n', '\n').split('\n') if l]
    out.append('ran %s' % found[0] if code == 0 else 'hook-failed %s exit %d' % (found[0], code))
    return out, 0 if code == 0 else 1

# ---------- entry point ----------


BOOLEAN = {'clear-stale'}


def parse_args(argv):
    opts = {'_': []}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith('--'):
            eq = a.find('=')
            if eq > 0:
                opts[a[2:eq]] = a[eq + 1:]
            elif a[2:] in BOOLEAN:
                opts[a[2:]] = True
            else:
                if i + 1 >= len(argv):
                    raise UsageError('%s needs a value' % a)
                i += 1
                opts[a[2:]] = argv[i]
        else:
            opts['_'].append(a)
        i += 1
    return opts


COMMANDS = {
    'stamp': cmd_stamp,
    'stamp-check': cmd_stamp_check,
    'spec-lint': cmd_spec_lint,
    'criteria-ids': cmd_criteria_ids,
    'gaps': cmd_gaps,
    'evidence-check': cmd_evidence_check,
    'begin': cmd_begin,
    'end': cmd_end,
    'markers': cmd_markers,
    'profile': cmd_profile,
    'event': cmd_event,
    'receipt': cmd_receipt,
}


def write_out(stream, text):
    stream.flush()
    stream.buffer.write(utf8(text))
    stream.buffer.flush()


def main(argv):
    command = argv[0] if argv else None
    try:
        fn = COMMANDS.get(command)
        if not fn:
            raise UsageError('unknown command "%s"; commands: %s' % (command or '', ', '.join(COMMANDS)))
        out, code = fn(parse_args(argv[1:]))
        if out:
            write_out(sys.stdout, '\n'.join(out) + '\n')
        return code
    except UsageError as e:
        write_out(sys.stderr, 'devfactory: %s\n' % e)
        return 2
    except Exception:
        write_out(sys.stderr, 'devfactory: %s' % traceback.format_exc())
        return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
