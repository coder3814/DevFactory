'use strict';

// Shared helpers for the devfactory.js tests. Holds no tests itself.

const fs = require('fs');
const os = require('os');
const path = require('path');
const childProcess = require('child_process');

const SCRIPT = path.resolve(__dirname, '..', 'devfactory.js');

function tempDir(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'devfactory-test-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

function run(args, cwd) {
  const r = childProcess.spawnSync(process.execPath, [SCRIPT, ...args], { cwd, encoding: 'utf8' });
  return { code: r.status, stdout: r.stdout, stderr: r.stderr, lines: r.stdout.split(/\r?\n/).filter(Boolean) };
}

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function git(cwd, ...args) {
  const r = childProcess.spawnSync(
    'git',
    ['-c', 'user.name=Test', '-c', 'user.email=test@example.com', '-c', 'commit.gpgsign=false', ...args],
    { cwd, encoding: 'utf8' }
  );
  if (r.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${r.stderr}`);
  return r.stdout.trim();
}

// A spec.md that passes spec-lint against criteria C1 and C2. Overrides replace parts.
function specText(o = {}) {
  const header = o.header || [
    ['Card', '#12'],
    ['Version', '1'],
    ['Status', o.status || 'Ready'],
    ['Card revision', o.revision || 'a'.repeat(64)],
    ['Repo commit', o.commit || 'abc1234'],
    ['Stamped', '2026-11-07'],
    ['Request type(s)', 'feature'],
  ];
  const sections = {
    'Decisions delegated to the developer': '- The cache key format.\n\n### Log\n\n- none yet',
    Boundaries: '### Excluded\n\n- Bulk import, because no caller needs it.\n\n### Edge behaviour\n\n| Criterion | Edge | Specified, excluded or delegated |\n|---|---|---|\n| C1 | empty input | returns an empty list |',
    Dispositions:
      o.dispositions ||
      '| Concern | Disposition | Demands (criterion or evidence row) |\n|---|---|---|\n| Existing data changed | Not applicable, because nothing is stored | |\n| Security | Not applicable, because the endpoint is unchanged | |\n| Performance | Not applicable, because the list is small | |\n| Release sequencing | Nothing before or after the deploy | |\n| Owner steps | One approval, below | |',
    'Interface surface': '**Determination:** not applicable, because nothing is rendered',
    'Evidence plan':
      o.evidence ||
      '| Criterion | Shown by | What it will show | Under what condition | Generated by | Checkpoint |\n|---|---|---|---|---|---|\n| C1 | test | the list | empty input | npm test | Local |\n| C2 | log | the count | a full run | npm run job | Local |',
    'Owner steps':
      o.owner ||
      '| Step | Who | Moment in the run |\n|---|---|---|\n| Approve the wording | the requester | before the build |',
    'Project bindings used': '- Test gate\n- Environment: Local',
    Amendments:
      o.amendments || '| Version | Date | What changed | Driven by |\n|---|---|---|---|\n| 1 | 2026-11-07 | Initial spec | — |',
  };
  const order = o.order || Object.keys(sections);
  const omit = o.omit || [];
  const body = order
    .filter((name) => !omit.includes(name))
    .map((name) => `## ${name}\n\n${sections[name]}\n`)
    .join('\n');
  const rows = header.map(([k, v]) => `| **${k}** | ${v} |`).join('\n');
  return `# Spec: Example card\n\n| | |\n|---|---|\n${rows}\n\n${body}`;
}

module.exports = { SCRIPT, tempDir, run, write, git, specText };
