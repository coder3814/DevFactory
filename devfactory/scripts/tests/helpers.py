"""Shared helpers for the devfactory.py tests. Holds no tests itself."""

import datetime
import importlib.util
import os
import shutil
import stat
import subprocess
import sys
import tempfile

SCRIPT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'devfactory.py'))


def load_script():
    spec = importlib.util.spec_from_file_location('devfactory_script', SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _remove_readonly(func, path, _):
    os.chmod(path, stat.S_IWRITE)
    func(path)


def remove_tree(path):
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=_remove_readonly)
    else:
        shutil.rmtree(path, onerror=_remove_readonly)


def temp_dir(test, prefix='devfactory-test-'):
    d = tempfile.mkdtemp(prefix=prefix)
    test.addCleanup(remove_tree, d)
    return d


class Result:
    def __init__(self, code, stdout, stderr):
        self.code = code
        self.stdout = stdout
        self.stderr = stderr
        self.lines = [l for l in stdout.replace('\r\n', '\n').split('\n') if l]


def run(args, cwd):
    r = subprocess.run([sys.executable, SCRIPT] + list(args), cwd=cwd, stdin=subprocess.DEVNULL,
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return Result(r.returncode, r.stdout.decode('utf-8'), r.stderr.decode('utf-8'))


def write(file, content):
    os.makedirs(os.path.dirname(file), exist_ok=True)
    with open(file, 'wb') as f:
        f.write(content.encode('utf-8'))


def read(file):
    with open(file, 'rb') as f:
        return f.read().decode('utf-8')


def git(cwd, *args):
    r = subprocess.run(['git', '-c', 'user.name=Test', '-c', 'user.email=test@example.com',
                        '-c', 'commit.gpgsign=false'] + list(args),
                       cwd=cwd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise RuntimeError('git %s failed: %s' % (' '.join(args), r.stderr.decode('utf-8', 'replace')))
    return r.stdout.decode('utf-8').strip()


def iso_ago(hours):
    t = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(hours=hours)
    return t.strftime('%Y-%m-%dT%H:%M:%S.') + '%03dZ' % (t.microsecond // 1000)


def parse_iso(s):
    return datetime.datetime.strptime(s.strip(), '%Y-%m-%dT%H:%M:%S.%fZ').replace(tzinfo=datetime.timezone.utc)


def spec_text(status=None, revision=None, commit=None, header=None, dispositions=None, evidence=None,
              owner=None, amendments=None, order=None, omit=()):
    """A spec.md that passes spec-lint against criteria C1 and C2. Arguments replace parts."""
    header = header or [
        ['Card', '#12'],
        ['Version', '1'],
        ['Status', status or 'Ready'],
        ['Card revision', revision or 'a' * 64],
        ['Repo commit', commit or 'abc1234'],
        ['Stamped', '2026-11-07'],
        ['Request type(s)', 'feature'],
    ]
    sections = {
        'Decisions delegated to the developer': '- The cache key format.\n\n### Log\n\n- none yet',
        'Boundaries': '### Excluded\n\n- Bulk import, because no caller needs it.\n\n### Edge behaviour\n\n| Criterion | Edge | Specified, excluded or delegated |\n|---|---|---|\n| C1 | empty input | returns an empty list |',
        'Dispositions': dispositions or
        '| Concern | Disposition | Demands (criterion or evidence row) |\n|---|---|---|\n| Existing data changed | Not applicable, because nothing is stored | |\n| Security | Not applicable, because the endpoint is unchanged | |\n| Performance | Not applicable, because the list is small | |\n| Release sequencing | Nothing before or after the deploy | |\n| Owner steps | One approval, below | |',
        'Interface surface': '**Determination:** not applicable, because nothing is rendered',
        'Evidence plan': evidence or
        '| Criterion | Shown by | What it will show | Under what condition | Generated by | Checkpoint |\n|---|---|---|---|---|---|\n| C1 | test | the list | empty input | npm test | Local |\n| C2 | log | the count | a full run | npm run job | Local |',
        'Owner steps': owner or
        '| Step | Who | Moment in the run |\n|---|---|---|\n| Approve the wording | the requester | before the build |',
        'Project bindings used': '- Test gate\n- Environment: Local',
        'Amendments': amendments or '| Version | Date | What changed | Driven by |\n|---|---|---|---|\n| 1 | 2026-11-07 | Initial spec | — |',
    }
    order = order or list(sections)
    body = '\n'.join('## %s\n\n%s\n' % (name, sections[name]) for name in order if name not in omit)
    rows = '\n'.join('| **%s** | %s |' % (k, v) for k, v in header)
    return '# Spec: Example card\n\n| | |\n|---|---|\n%s\n\n%s' % (rows, body)
